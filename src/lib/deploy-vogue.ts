// ─── Types ────────────────────────────────────────────────────────────────────

export type VoguePrivateState = {
  ownerSecret: Uint8Array;
};

export type DeployResult = {
  contractAddress: string;
  transactionId: string;
  network: string;
  deployedAt: string;
  explorerContractUrl: string;
  explorerTxUrl: string;
};

type DeployTxData = {
  public: { contractAddress: string };
  private: {
    unprovenTx: unknown;
    initialPrivateState: VoguePrivateState;
    signingKey?: unknown;
  };
};

// ─── Private State ────────────────────────────────────────────────────────────

export function createInitialPrivateState(
  ownerSecret?: Uint8Array
): VoguePrivateState {
  const secret = ownerSecret ?? crypto.getRandomValues(new Uint8Array(32));
  if (secret.length !== 32) throw new Error("Owner secret must be 32 bytes.");
  return { ownerSecret: secret };
}

