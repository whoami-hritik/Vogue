/**
 * Vogue — Real On-Chain Contract Deployment via 1AM Wallet
 *
 * Ported from Aquas's proven working deploy-doctor-license.ts pattern.
 * Uses the real Midnight SDK:
 *   - CompiledContract.make() from @midnight-ntwrk/compact-js
 *   - createUnprovenDeployTx() + submitTxAsync() from @midnight-ntwrk/midnight-js-contracts
 *
 * The contract address is DETERMINISTIC — known before submission.
 * submitTxAsync is fire-and-forget; we resolve immediately when 1AM confirms
 * (before the indexer finishes polling) to avoid the spinner hanging.
 *
 * Prerequisites:
 *   1. contracts/managed/vogue/contract/index.js  — compiled TypeScript bindings
 *   2. public/zk/vogue/keys/*.prover / *.verifier — per-circuit proving/verifying keys
 *   3. public/zk/vogue/zkir/*.zkir / *.bzkir      — circuit IR bytecode
 *
 * Generated by running:
 *   compact compile "+0.31.1" contracts/vogue.compact contracts/managed/vogue
 *   cp -R contracts/managed/vogue/keys public/zk/vogue/keys
 *   cp -R contracts/managed/vogue/zkir public/zk/vogue/zkir
 */

